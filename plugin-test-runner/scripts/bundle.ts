// Builds plugin-test-runner/vendor: the part of this repository the runner needs, so the package
// stands alone (published to JSR, it cannot import repository paths).
//
//   deno run --allow-read --allow-write plugin-test-runner/scripts/bundle.ts
//
// vendor/ holds a copy of the Plugin Host (plugin-host/src, without the Plugin Manager's web page,
// which the runner never serves) and of the seam 2 stand-ins (tests/seam2/support: host, bridge and
// Komga). The relative layout is kept, so the copied files import each other unchanged. The two
// places that find modules by reading a folder (routes, migrations) are replaced with static
// lists, because a published package has no folder to read. vendor/ is generated, never edited,
// and not committed; seam 2's runner and its Dockerfile build it first.
import { cp, mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const packageDir = fileURLToPath(new URL("..", import.meta.url));
const repoRoot = join(packageDir, "..");
const vendor = join(packageDir, "vendor");
const hostOut = join(vendor, "plugin-host", "src");
const supportOut = join(vendor, "tests", "seam2", "support");

await rm(vendor, { recursive: true, force: true });
await mkdir(supportOut, { recursive: true });

await cp(join(repoRoot, "plugin-host", "src"), hostOut, {
  recursive: true,
  filter: (source) => {
    const path = source.replaceAll("\\", "/");
    return !path.includes("/plugin-host/src/manager") && !path.endsWith("/routes/manager-ui.ts");
  },
});
for (const file of ["host.ts", "fake-bridge.ts", "fake-komga.ts"]) {
  await cp(join(repoRoot, "tests", "seam2", "support", file), join(supportOut, file));
}

const tsFiles = async (dir: string) => (await readdir(dir)).filter((f) => f.endsWith(".ts")).sort();

const routes = await tsFiles(join(hostOut, "http", "routes"));
await writeFile(
  join(hostOut, "http", "route-modules.ts"),
  `// Generated by plugin-test-runner/scripts/bundle.ts: the route modules, listed statically.
import type { Router } from "./router.ts";
${routes.map((f, i) => `import * as route${i} from "./routes/${f}";`).join("\n")}

export interface RouteModule {
  register(router: Router): void;
}

export function loadRouteModules(): Promise<RouteModule[]> {
  return Promise.resolve([${routes.map((_, i) => `route${i}`).join(", ")}]);
}
`,
  { encoding: "utf8" },
);

const migrations = await tsFiles(join(hostOut, "db", "migrations"));
await writeFile(
  join(hostOut, "db", "migration-modules.ts"),
  `// Generated by plugin-test-runner/scripts/bundle.ts: the migrations, listed statically.
import type { DatabaseSync } from "node:sqlite";
${migrations.map((f, i) => `import * as migration${i} from "./migrations/${f}";`).join("\n")}

export interface Migration {
  name: string;
  up(db: DatabaseSync): void;
}

export function loadMigrations(): Promise<Migration[]> {
  return Promise.resolve([
${migrations.map((f, i) => `    { name: ${JSON.stringify(f)}, up: migration${i}.up },`).join("\n")}
  ]);
}
`,
  { encoding: "utf8" },
);

console.log(`vendor built: ${routes.length} routes, ${migrations.length} migrations`);
